#!/usr/bin/env python3
"""Generates the corpus files whose source is too repetitive to write by hand:
  c04_big_ctor.v        constructors of arity 60 and 300
  c07_ord_ge_251.v      260 non-nullary constructors (boxed ordinal 251)
  c14_chunk_large.v     one straight-line chunk of 2000 conses (6000 words)
  c15_chunk_over_nursery.v  one chunk of 22000 conses (66000 words > nursery)
Run from this directory: python3 gen_corpus.py"""

D7 = """Inductive d7 := D0 | D1 | D2 | D3 | D4 | D5 | D6.
Definition s7 (d : d7) : d7 :=
  match d with D0 => D1 | D1 => D2 | D2 => D3 | D3 => D4 | D4 => D5 | D5 => D6 | D6 => D0 end.
Definition add7 (x y : d7) : d7 :=
  match x with
  | D0 => y | D1 => s7 y | D2 => s7 (s7 y) | D3 => s7 (s7 (s7 y))
  | D4 => s7 (s7 (s7 (s7 y))) | D5 => s7 (s7 (s7 (s7 (s7 y))))
  | D6 => s7 (s7 (s7 (s7 (s7 (s7 y))))) end.
(* [hide 0 v] is [v], through a recursive function the optimizer does not
   inline, so that [v]'s constructor is not known statically
   (case-of-known-constructor would otherwise remove the allocation). *)
Fixpoint hide {A} (n : nat) (a : A) : A := match n with O => a | S m => hide m a end.
"""

def big_ctor():
    n1, n2 = 60, 300
    f1 = " ".join(f"(a{i} : d7)" for i in range(n1))
    f2 = " ".join(f"(b{i} : d7)" for i in range(n2))
    pats1 = " ".join(f"a{i}" for i in range(n1))
    pats2 = " ".join(f"b{i}" for i in range(n2))
    # fields: field i = s7^i x  (computed by iterating s7, so not constant)
    mk1 = "\n".join(f"  let a{i} := s7 a{i-1} in" for i in range(1, n1))
    mk2 = "\n".join(f"  let b{i} := s7 b{i-1} in" for i in range(1, n2))
    sum1 = " (".join(f"add7 a{i}" for i in range(n1)) + " D0" + ")" * (n1 - 1)
    sum2 = " (".join(f"add7 b{i}" for i in range(0, n2, 7)) + " D0" + ")" * (len(range(0, n2, 7)) - 1)
    return f"""(* Large constructors: [Big60] has 60 fields (61-word objects), [Big300]
   has 300 fields (301 words).  10^4 [Big60] records (610K words, ~10
   nursery overflows) are kept in a list and then folded; a [Big300] record
   is live across all of it.  Each object is allocated as a single chunk
   (one limit check for 61 / 301 words).
   Generated by gen_corpus.py.
   Targets: Econstr with large arity (header arity<<10|ord, chunk_words),
   Eproj with large offsets, roots_ok for big objects, room.
   Expected: see prog_expected below. *)
From Stdlib Require Import PArith.
{D7}
Inductive big60 := Big60 {f1}.
Inductive big300 := Big300 {f2}.

Definition mk60 (a0 : d7) : big60 :=
{mk1}
  Big60 {pats1}.

Definition mk300 (b0 : d7) : big300 :=
{mk2}
  Big300 {pats2}.

Definition sum60 (r : big60) : d7 :=
  match r with Big60 {pats1} => {sum1} end.

Definition sum300 (r : big300) : d7 :=
  match r with Big300 {pats2} => {sum2} end.

Definition last60 (r : big60) : d7 := match r with Big60 {pats1} => a{n1-1} end.
Definition last300 (r : big300) : d7 := match r with Big300 {pats2} => b{n2-1} end.

Fixpoint build (n : list unit) (x : d7) (acc : list big60) : list big60 :=
  match n with nil => acc | cons _ m => build m (s7 x) (cons (mk60 x) acc) end.

Fixpoint fold (l : list big60) (acc : d7) : d7 :=
  match l with nil => acc | cons r l' => fold l' (add7 (sum60 r) (add7 (last60 r) acc)) end.

Definition prog : d7 * d7 * d7 :=
  let big := hide 0 (mk300 D3) in
  let l := build (Pos.iter (cons tt) nil 10000) D1 nil in
  let s := fold l D0 in
  (s, sum300 big, last300 big).
"""

def ord_ge_251():
    n = 260
    ctors = "\n".join(f"  | K{i} (l : list d7)" for i in range(n))
    return f"""(* Boxed constructor ordinals >= 251.  [wide] has {n} constructors, all
   with one field, so their (boxed) ordinals are 0..{n-1}.  The Rocq contract
   allows ordinals < 1024 ([tag_ok]) and the header is arity<<10 | ord, but
   gc_stack.c reads the tag as hd & 0xFF and treats tags >= 251 (No_scan_tag)
   as raw data whose fields are NOT scanned.  An object [K251 l] whose list
   [l] is still in the nursery at a collection therefore keeps a dangling
   pointer after it: this program is EXPECTED TO FAIL under gc_stack.c
   (gc_stack_checked.c reports a roots_ok violation mentioning No_scan_tag;
   the unchecked runtime returns garbage or crashes).  It is correct under
   the Rocq semantics.
   Generated by gen_corpus.py.
   Targets: tag_ok vs. the runtime's header interpretation (Ecase boxed
   switch on ord & 1023; GC scanning).
   Expected: see prog_expected below. *)
From Stdlib Require Import PArith.
{D7}
Inductive wide :=
{ctors}.

Definition get (w : wide) : list d7 :=
  match w with K251 l => l | K252 l => l | K0 l => l | K255 l => l | _ => nil end.

Fixpoint sum (l : list d7) (acc : d7) : d7 :=
  match l with nil => acc | cons x l' => sum l' (add7 x acc) end.

(* Allocate enough garbage to force several collections while [w] is live. *)
Fixpoint churn (n : list unit) (acc : list d7) : d7 :=
  match n with nil => sum acc D0 | cons _ m => churn m (cons D1 nil) end.

Definition mk (n : positive) (x : d7) : list d7 := Pos.iter (cons x) nil n.

Definition prog : d7 * d7 * d7 * d7 :=
  let w251 := hide 0 (K251 (mk 1000 D2)) in
  let w255 := hide 0 (K255 (mk 999 D3)) in
  let w250 := hide 0 (K250 (mk 50 D1)) in
  let c := churn (Pos.iter (cons tt) nil 300000) nil in
  (sum (get w251) D0, sum (get w255) D0, sum (get w250) c, c).
"""

def chunk(n, name, words, extra):
    elems = "; ".join("x" for _ in range(n))
    return f"""(* One straight-line allocation chunk of {n} cons cells ({words} words):
   [x :: x :: ... :: nil] with [x] a function argument (so the list is not a
   closed constant and is built at run time, one Econstr after the other, in
   one chunk with a single limit check for all {words} words).
{extra}
   Generated by gen_corpus.py.
   Expected: see prog_expected below. *)
From Stdlib Require Import List.
Import ListNotations.
{D7}
Definition lit (x : d7) : list d7 := [{elems}].

Fixpoint sum (l : list d7) (acc : d7) : d7 :=
  match l with nil => acc | cons y l' => sum l' (add7 y acc) end.

Fixpoint rep (n : nat) (x : d7) (acc : d7) : d7 :=
  match n with O => acc | S m => rep m (s7 x) (add7 (sum (lit x) D0) acc) end.

Definition prog : d7 := rep 40 D1 D0.
"""

files = {
  "c04_big_ctor.v": big_ctor(),
  "c07_ord_ge_251.v": ord_ge_251(),
  "c14_chunk_large.v": chunk(2000, "c14", 6000,
    "   40 repetitions: the chunk's limit check fails about every 10th time and\n"
    "   calls the collector with nalloc = 6000.\n"
    "   Targets: chunk_words / the batched limit check, room with a large\n"
    "   nalloc, the llvm_restricted chunk-size clause."),
  "c15_chunk_over_nursery.v": chunk(22000, "c15", 66000,
    "   66000 words exceed gc_stack.c's fixed nursery (NURSERY_SIZE = 65536\n"
    "   words), so the collector is called with nalloc = 66000 and\n"
    "   gc_stack.c's resume() calls exit(1) (\"Nursery is too small for\n"
    "   function's num_allocs\").  The contract ([runtime_correct]) requires\n"
    "   room or out-of-memory for every nalloc < 2^61, so this program is\n"
    "   EXPECTED TO FAIL under gc_stack.c (gc_stack_checked.c reports a\n"
    "   [room] violation); it is within [llvm_restricted].\n"
    "   Targets: room / the nalloc bound."),
}
# Expected values (computed with vm_compute; re-checked by prog_expected in
# each generated file) and the S-expression the driver should print.
EXPECTED = {
  "c04_big_ctor.v": ("(D2, D3, D1)", "(C0 (C0 2 3) 1)"),
  "c07_ord_ge_251.v": ("(D5, D1, D1, D1)", "(C0 (C0 (C0 5 1) 1) 1)"),
  "c14_chunk_large.v": ("D5", "5"),
  "c15_chunk_over_nursery.v": ("D6", "6"),
}
for name, text in files.items():
    r, sx = EXPECTED[name]
    text = text.replace("   Expected: see prog_expected below. *)",
                        f"   Expected (Rocq): {r}\n   EXPECTED: {sx} *)")
    assert "EXPECTED: " in text, name
    text += f"\nExample prog_expected : prog = {r} := ltac:(vm_compute; reflexivity).\n"
    with open(name, "w") as f:
        f.write(text)
